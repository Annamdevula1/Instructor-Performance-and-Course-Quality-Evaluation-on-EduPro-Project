# Missing KPI Calculations

# 1. Rating Consistency Index
rating_consistency_index = (
    1 - (df["TeacherRating"].std() / df["TeacherRating"].mean())
)

# 2. Experience Impact Score
experience_impact_score = df["YearsOfExperience"].corr(
    df["TeacherRating"]
)

# 3. Enrollment Influence Ratio
high_rated_enrollments = df.loc[
    df["TeacherRating"] >= 4,
    "TransactionID"
].nunique()

total_enrollments = df["TransactionID"].nunique()

enrollment_influence_ratio = (
    high_rated_enrollments / total_enrollments
)

# Display KPI values
print("Rating Consistency Index:", round(rating_consistency_index, 3))
print("Experience Impact Score:", round(experience_impact_score, 3))
print("Enrollment Influence Ratio:", round(enrollment_influence_ratio, 3))

